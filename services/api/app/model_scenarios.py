"""Reproducible, versioned, SIMULATED flood-style scenarios.

No real historical flood records are loaded. Labels come from an artificial
rule with simulated noise: these are software tests, NOT field evidence.
"""
import math

SEED = 20261016


def generate() -> dict:
    state = SEED

    def rand() -> float:
        nonlocal state
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        state &= 0xFFFFFFFF
        return state / 4294967296.0

    scenarios = []
    for group in range(24):
        # Related observations stay in the same partition to avoid row leakage.
        base_rain = 6 + ((group * 37) % 140)
        base_water = 5 + ((group * 19) % 90)
        drainage = ("good", "moderate", "limited")[group % 3]
        for step in range(9):
            rainfall = round(max(0, min(200, base_rain + (rand()*2-1)*22)), 3)
            water = round(max(0, min(100, base_water + (rand()*2-1)*15)), 3)
            synthetic_latent = -3.5 + 0.035*rainfall + 0.027*water + {
                "good": 0, "moderate": 0.65, "limited": 1.1
            }[drainage]
            simulated_probability = 1/(1+math.exp(-synthetic_latent))
            artificial_label = int(rand() < simulated_probability)
            scenarios.append({
                "scenario_id": group, "time_index": step,
                "rainfall_mm_hour": rainfall, "water_index": water,
                "drainage_condition": drainage, "synthetic_label": artificial_label,
                "split": "train" if group < 18 else "holdout",
            })
    return {
        "dataset_version": "aegis.exercise.scenarios.v1",
        "source": "synthetic_generated_fixture",
        "generator_seed": SEED,
        "description": "Fictional labels generated by a synthetic logistic rule; NOT real disaster evidence.",
        "scenarios": scenarios,
    }
